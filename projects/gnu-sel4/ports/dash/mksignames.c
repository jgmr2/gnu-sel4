/*
 * signames.c generator for dash on GNU/seL4.
 *
 * Replaces the original mksignames.c (which comes from GNU bash and is GPL)
 * with a fixed table of the Linux x86_64 signals, the numbering musl uses.
 * That way dash stays entirely under its BSD license.
 *
 * SPDX-License-Identifier: BSD-2-Clause
 */
#include <stdio.h>

#define NSIG_ 65   /* musl's _NSIG */

static const char *const names[32] = {
    "EXIT", "HUP", "INT", "QUIT", "ILL", "TRAP", "ABRT", "BUS",
    "FPE", "KILL", "USR1", "SEGV", "USR2", "PIPE", "ALRM", "TERM",
    "STKFLT", "CHLD", "CONT", "STOP", "TSTP", "TTIN", "TTOU", "URG",
    "XCPU", "XFSZ", "VTALRM", "PROF", "WINCH", "IO", "PWR", "SYS",
};

int main(int argc, char **argv)
{
    FILE *out = fopen(argc > 1 ? argv[1] : "signames.c", "w");   /* like the original */
    if (!out) return 1;
    fprintf(out, "/* Generated by mksignames (GNU/seL4). Do not edit. */\n\n");
    fprintf(out, "#include <signal.h>\n\n");
    fprintf(out, "const char *const signal_names[NSIG + 1] = {\n");
    for (int i = 0; i < NSIG_; i++) {
        if (i < 32) fprintf(out, "    \"%s\",\n", names[i]);
        else fprintf(out, "    \"%d\",\n", i);           /* real-time signals: by number */
    }
    fprintf(out, "    (char *)0x0\n};\n");
    return fclose(out);
}
