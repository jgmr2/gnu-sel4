"""gen-sysmap.py <musl-source> > rt_sysmap.h: the runtime's system call numbers.

posix_server speaks Linux x86_64's numbers on every architecture (the protocol). This header
(1) defines every SYS_name with its x86_64 number, overriding the architecture's own from
<sys/syscall.h>, and (2) for aarch64, maps musl's numbers (asm-generic) to them by name; -1
where there is none."""
import re, sys

def table(musl, arch):
    d = {}
    for line in open(f"{musl}/arch/{arch}/bits/syscall.h.in"):
        m = re.match(r"#define __NR_(\w+)\s+(\d+)", line)
        if m:
            d[m.group(1)] = int(m.group(2))
    return d

musl = sys.argv[1]
x86, arm = table(musl, "x86_64"), table(musl, "aarch64")
out = ["/* generated by tools/gen-sysmap.py from musl: do not edit */", "#pragma once"]
for name, nr in sorted(x86.items(), key=lambda kv: kv[1]):
    out += [f"#undef SYS_{name}", f"#define SYS_{name} {nr}"]
top = max(arm.values())
m = [-1] * (top + 1)
for name, nr in arm.items():
    if name in x86:
        m[nr] = x86[name]
out += ["#ifdef __aarch64__", f"static const short sysmap_aarch64[{top + 1}] = {{"]
out += ["    " + ", ".join(str(v) for v in m[i:i + 16]) + "," for i in range(0, top + 1, 16)]
out += ["};", "#endif"]
print("\n".join(out))
