/*
 * GNU/seL4 <-> Linux VM bridge (like WSL "interop").
 *
 * posix_server and the VM share a byte channel: to Linux it is a vsock
 * connection to the host (port BR_VSOCK_PORT), opened by sel4-agent (vm/agent/). Frames of
 * multiplexed sessions travel over the channel; each session is a command run
 * in the VM on behalf of a native program (apps/linux: /bin/linux, /bin/docker...).
 *
 * Frame on the channel:  struct br_frame + `len` bytes of data
 *
 * On the native side, a program opens /dev/linux (one session) and speaks in
 * "records": each write() is one record [type][data...] and each read()
 * returns one. posix_server adds/strips the session number.
 *
 * SPDX-License-Identifier: BSD-2-Clause
 */
#pragma once
#include <stdint.h>

struct br_frame {
    uint8_t  type;
    uint8_t  pad;
    uint16_t session;
    uint32_t len;
};

#define BR_MAX_DATA   32768        /* maximum data per frame/record */
#define BR_VSOCK_PORT 5000         /* the agent connects to the host (CID 2) on this vsock port */

enum br_type {
    /* agent -> server */
    BR_HELLO     = 1,              /* the agent started (earlier sessions are dead) */
    BR_STDOUT    = 16,             /* the command's standard output */
    BR_STDERR    = 17,             /* standard error */
    BR_EXIT      = 18,             /* finished: data = int32 code (0..255; 128+signal) */

    /* native program -> agent */
    BR_OPEN      = 2,              /* data = struct br_open + argv (\0-terminated strings) */
    BR_STDIN     = 3,              /* data for standard input */
    BR_STDIN_EOF = 4,              /* end of standard input */
    BR_SIGNAL    = 5,              /* data = int32 signal for the command's group */
    BR_WINSIZE   = 6,              /* data = uint16 rows, uint16 columns */
    BR_CLOSE     = 7,              /* (generated by the server when the session closes) */
};

#define BR_OPEN_TTY   1            /* run with a terminal (pty): interactive mode */

struct br_open {
    uint32_t flags;
    uint16_t rows, cols;
    uint32_t argc;
    /* followed by argc strings */
};
